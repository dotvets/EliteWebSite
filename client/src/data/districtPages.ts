const DISTRICT_SLUGS = new Set<string>(DISTRICT_PAGES.map((d) => d.slug));

export function normalizeDistrictSlug(
  value: string | null | undefined,
): DistrictSlug | null {
  const slug = (value || "").trim().toLowerCase();
  return DISTRICT_SLUGS.has(slug) ? (slug as DistrictSlug) : null;
}
